package config

import (
	"fmt"
	"os"
	"strings"

	yaml "gopkg.in/yaml.v2"
)

// Config defines the p4p log input and Prometheus textfile output.
type Config struct {
	P4PLog               string `yaml:"p4p_log"`
	MetricsOutput        string `yaml:"metrics_output"`
	SDPInstance          string `yaml:"sdp_instance"`
	PollIntervalSeconds  int    `yaml:"poll_interval_seconds"`
	ReadAll              bool   `yaml:"read_all"`
	FailOnMissingLogfile bool   `yaml:"fail_on_missing_logfile"`
}

// SampleConfig is a complete configuration template emitted by
// p4proxyprometheus --sample.config.
const SampleConfig = `
# Sample p4proxyprometheus configuration file - normally called p4proxyprometheus.yaml
# Generated by: p4proxyprometheus --sample.config
# Edit as required - see comments below
# Blank lines and lines starting with # are comments and ignored

# ----------------------
# p4p_log: REQUIRED! Path to the p4p structured log.
p4p_log: /p4/1/logs/p4p.log

# ----------------------
# metrics_output: REQUIRED! Name of output file to write for processing by node_exporter.
# For SDP it will add p4_proxy-<SDP_INSTANCE>.prom.
# Ensure that node_exporter service user has read access to this folder.
metrics_output: /p4/metrics/p4_proxy.prom

# ----------------------
# sdp_instance: REQUIRED! SDP instance - typically integer, but can be alphanumeric.
# See: https://swarm.workshop.perforce.com/projects/perforce-software-sdp for more.
sdp_instance: "1"

# ----------------------
# poll_interval_seconds: How often to poll for log updates. Set to 0 to use
# filesystem notifications instead of polling.
poll_interval_seconds: 1

# ----------------------
# read_all: Process the current log contents on startup. Keep false for normal
# continuous operation.
read_all: false

# ----------------------
# fail_on_missing_logfile: Allow startup before p4p creates the log file.
fail_on_missing_logfile: false
`

// LoadConfigFile loads and validates a YAML configuration file.
func LoadConfigFile(filename string) (*Config, error) {
	content, err := os.ReadFile(filename)
	if err != nil {
		return nil, fmt.Errorf("read configuration %q: %w", filename, err)
	}

	cfg := &Config{
		PollIntervalSeconds: 1,
	}
	if err := yaml.Unmarshal(content, cfg); err != nil {
		return nil, fmt.Errorf("parse configuration %q: %w", filename, err)
	}
	if err := cfg.Validate(); err != nil {
		return nil, fmt.Errorf("validate configuration %q: %w", filename, err)
	}
	return cfg, nil
}

// Validate ensures that all required settings are usable.
func (c *Config) Validate() error {
	if strings.TrimSpace(c.P4PLog) == "" {
		return fmt.Errorf("p4p_log must be specified")
	}
	if strings.TrimSpace(c.MetricsOutput) == "" {
		return fmt.Errorf("metrics_output must be specified")
	}
	if !strings.HasSuffix(c.MetricsOutput, ".prom") {
		return fmt.Errorf("metrics_output must end in .prom")
	}
	if strings.TrimSpace(c.SDPInstance) == "" {
		return fmt.Errorf("sdp_instance must be specified")
	}
	if c.PollIntervalSeconds < 0 {
		return fmt.Errorf("poll_interval_seconds must be zero or greater")
	}
	return nil
}
